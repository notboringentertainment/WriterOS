// Canonical JSON and SHA-256 for look hashes.
//
// look_hash must equal OpenMontage's record_sha256 (lib/canonical_json.py) byte
// for byte. This is the OpenMontage-compatible subset of RFC 8785: strings
// (keys and values) NFC-normalised, keys sorted by UTF-16 code units, JCS string
// escapes, ES6 number formatting, no whitespace. Anything outside the subset
// throws instead of hashing: non-finite numbers, integers beyond the JS safe
// range (OpenMontage prints big Python ints as digits; JS cannot represent them),
// lone surrogates, and values JSON cannot carry. Pinned by
// tests/fixtures/lookSpec/vectors.json, generated by OpenMontage.
//
// Runs in the browser and on the server, so SHA-256 is implemented here rather
// than taken from node:crypto.

export class CanonicalJsonError extends Error {}

const SHORT_ESCAPES: Record<string, string> = {
  '\b': '\\b',
  '\t': '\\t',
  '\n': '\\n',
  '\f': '\\f',
  '\r': '\\r',
  '"': '\\"',
  '\\': '\\\\',
}

function escapeString(value: string): string {
  if (/[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/.test(value)) {
    throw new CanonicalJsonError('A string contains a lone surrogate and cannot be hashed.')
  }
  let out = '"'
  for (const ch of value.normalize('NFC')) {
    const short = SHORT_ESCAPES[ch]
    if (short !== undefined) out += short
    else if (ch.charCodeAt(0) < 0x20) out += `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`
    else out += ch
  }
  return `${out}"`
}

function formatNumber(value: number): string {
  if (!Number.isFinite(value)) throw new CanonicalJsonError('NaN and Infinity cannot be hashed.')
  if (Number.isInteger(value) && !Number.isSafeInteger(value)) {
    throw new CanonicalJsonError(`The number ${value} is outside the safe integer range and cannot be hashed.`)
  }
  return Object.is(value, -0) ? '0' : String(value)
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  if (typeof value !== 'object' || value === null) return false
  const prototype = Object.getPrototypeOf(value)
  return prototype === Object.prototype || prototype === null
}

function serialize(value: unknown, out: string[]): void {
  if (value === null) {
    out.push('null')
  } else if (value === true || value === false) {
    out.push(String(value))
  } else if (typeof value === 'number') {
    out.push(formatNumber(value))
  } else if (typeof value === 'string') {
    out.push(escapeString(value))
  } else if (Array.isArray(value)) {
    out.push('[')
    value.forEach((item, index) => {
      if (item === undefined) throw new CanonicalJsonError('Arrays cannot hold undefined.')
      if (index) out.push(',')
      serialize(item, out)
    })
    out.push(']')
  } else if (isPlainObject(value)) {
    const entries: Array<[string, unknown]> = []
    const seen = new Set<string>()
    for (const [key, member] of Object.entries(value)) {
      if (member === undefined) continue
      const normalized = key.normalize('NFC')
      if (seen.has(normalized)) throw new CanonicalJsonError(`Two keys are the same after normalisation: ${normalized}`)
      seen.add(normalized)
      entries.push([normalized, member])
    }
    // Default string comparison is by UTF-16 code units, which is what JCS requires.
    entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    out.push('{')
    entries.forEach(([key, member], index) => {
      if (index) out.push(',')
      out.push(escapeString(key), ':')
      serialize(member, out)
    })
    out.push('}')
  } else {
    throw new CanonicalJsonError(`A ${typeof value} value cannot be hashed.`)
  }
}

export function canonicalJson(value: unknown): string {
  const out: string[] = []
  serialize(value, out)
  return out.join('')
}

